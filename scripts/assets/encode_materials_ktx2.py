"""Encodes every runtime material map to KTX2 beside its PNG and records sizes.

Usage: python3 -I scripts/assets/encode_materials_ktx2.py [--ktx <path to ktx>]

UASTC (transcodes to ASTC 4x4 on Quest 3, 8 bits per pixel on the GPU) with RDO and Zstandard
supercompression, full mip chain generated by the encoder. Colour roles are sRGB; normal and ORM
are linear data. Writes public/assets/materials/ktx2-report.json.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RUNTIME = ROOT / "public/assets/materials"
DEFAULT_KTX = Path.home() / ".local/opt/ktx-software-4.4.2/bin/ktx"
COLOR_ROLES = {"basecolor", "emissive"}


def gpu_bytes(size: int) -> int:
    """ASTC 4x4: 16 bytes per 4x4 block, summed over the mip chain down to 1x1."""
    total = 0
    while True:
        blocks = max(1, (size + 3) // 4)
        total += blocks * blocks * 16
        if size == 1:
            return total
        size //= 2


def encode(ktx: Path, png: Path, role: str) -> Path:
    out = png.with_suffix(".ktx2")
    color = role in COLOR_ROLES
    cmd = [
        str(ktx), "create",
        "--format", "R8G8B8_SRGB" if color else "R8G8B8_UNORM",
        "--assign-tf", "srgb" if color else "linear",
        "--encode", "uastc", "--uastc-quality", "2", "--uastc-rdo",
        "--zstd", "18", "--generate-mipmap",
        # three.js flips PNGs on upload (flipY) but cannot flip compressed data, so the rows are
        # stored bottom-up here. Orientation and normal-map green then match the PNG path exactly.
        "--convert-texcoord-origin", "bottom-left",
    ]
    if role == "normal":
        cmd.append("--normalize")
    subprocess.run([*cmd, str(png), str(out)], check=True)
    return out


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--ktx", type=Path, default=DEFAULT_KTX)
    args = parser.parse_args()
    version = subprocess.run([str(args.ktx), "--version"], check=True, capture_output=True, text=True).stdout.strip()
    manifest = json.loads((RUNTIME / "materials.json").read_text())
    report: dict = {
        "tool": version,
        "settings": "uastc q2 rdo, zstd 18, generated mips, texcoord origin bottom-left",
        "files": {},
    }
    for name, entry in manifest.items():
        for role, file in entry["maps"].items():
            png = RUNTIME / name / file
            out = encode(args.ktx, png, role)
            report["files"][f"{name}/{out.name}"] = {
                "role": role,
                "png_bytes": png.stat().st_size,
                "ktx2_bytes": out.stat().st_size,
                "gpu_bytes_astc4x4": gpu_bytes(1024),
                "sha256": hashlib.sha256(out.read_bytes()).hexdigest(),
            }
            print(f"{name}/{out.name}: {out.stat().st_size / 1e6:.2f} MB (png {png.stat().st_size / 1e6:.2f} MB)")
    files = report["files"].values()
    report["totals"] = {
        "png_bytes": sum(f["png_bytes"] for f in files),
        "ktx2_bytes": sum(f["ktx2_bytes"] for f in files),
        "gpu_bytes_astc4x4": sum(f["gpu_bytes_astc4x4"] for f in files),
        "gpu_bytes_uncompressed_rgba8": sum(gpu_bytes(1024) * 4 for _ in files),
    }
    (RUNTIME / "ktx2-report.json").write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps(report["totals"]))


if __name__ == "__main__":
    main()
